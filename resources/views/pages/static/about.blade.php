<p data-sourcepos="7:1-7:483" style="text-align:justify;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="color:#666666;"><strong>With a long-term vision,</strong> we have continuously expanded our operations, investing heavily in a clean production plant, modern machinery and equipment, applying automation in production, digitalizing management, and training our employees. To date, we have over <strong>50 injection molding machines</strong>, over <strong>180 officers and workers</strong>, with a production capacity of over <strong>200 tons/month</strong>. All of this is aimed at better meeting the needs of our customers and helping them grow stronger together.</span></span></span></p>



<p data-sourcepos="9:1-9:471" style="text-align:justify;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="color:#666666;"><strong>Nhi Binh Plastic manufactures a wide variety of products</strong> such as household plastic, pet toys, children's toys, technical plastic parts, plastic accessories for the woodworking, textile, and medical industrie,etc.. All products are manufactured according to customer requirements from product design to mold making, injection molding, printing, assembly, and complete packaging. We always strive to provide not only plastic products but also the <strong>best solutions for our customers</strong>.</span></span></span></p>



<p data-sourcepos="11:1-11:261" style="text-align:justify;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="color:#666666;"><strong>Nhi Binh Plastic's products are suplied to many companies in Vietnam</strong> as well as exported to many countries around the world such as the USA, Japan, and Europe,etc… We are committed to using all our resources to provide high-quality, environmentally friendly products, competitive prices, and fast delivery.</span></span></span></p>



<p data-sourcepos="13:1-13:260" style="text-align:justify;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="color:#666666;"><strong>Nhi Binh Plastic's products are strictly inspected,</strong> from input to output, to meet international standards such as BSCI, ISO 9001:2015, ISO 14001:2015, and RoHS, FDA, REACH standards. The quality of all products is guaranteed to be as promised to customers.</span></span></span></p>



<p data-sourcepos="15:1-15:428" style="text-align:justify;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="color:#666666;"><strong>With the motto "People-oriented",</strong> we always create a friendly working environment with many policies to care for and support all our employees. The cohesion between production, business, quality control, sales, and delivery departments ensures that the process of receiving and handling customer requests is quick and convenient, creating a solid foundation for the development of Nhi Binh Plastic in the present and future.</span></span></span></p>



