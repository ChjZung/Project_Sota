	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Extended Warranty:</strong> If customers entrust Nhi Binh Plastic with the production of plastic products using the molds, the warranty period for the molds is extended up to 60 months.</span></span></span></span></li>

</ul>



<h3 style="text-align: justify;"><span style="color:#666666;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;">Mold Warranty Coverage</span></span></span></strong></span></h3>



