            <div class="content-main w-clear" id="toc-content"><p style="text-align: center;"><span style="font-size:20px;"><strong><span style="font-family:Arial,Helvetica,sans-serif;"><span style="line-height:1.1;"><span style="color:#666666;">The Journey of Formation and Development of </span><span style="color:#e74c3c;">Nhi Binh Plastic</span></span></span></strong></span><br />

 </p>



<p style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;">From humble beginnings with a small workshop, Nhi Binh Plastic has grown into one of the leading plastic manufacturing companies. This journey is a testament to perseverance, creativity, unity, and a strong commitment to sustainable development.</span></span></span></span></p>



<p style="text-align: center;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><img alt="History of Nhi Binh Plastic" src="/upload/elfinder/_History%20of%20Nhi%20Binh%20Plastic.jpg" style="width: 800px; height: 2000px;" /></span></span></span></span></p>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="font-family:Arial,Helvetica,sans-serif;"><span style="line-height:1.1;"><span style="color:#666666;">Early Stages</span></span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2009:</strong> Nhi Binh Plastic was founded in Binh Chanh District, Ho Chi Minh City, with two injection molding machines, marking the first steps in building its brand.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2010:</strong> The company relocated its factory to Hoc Mon District, Ho Chi Minh City, adding 13 more injection molding machines, bringing the total to 15, expanding production capacity, and enhancing supply capabilities.</span></span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="font-family:Arial,Helvetica,sans-serif;"><span style="line-height:1.1;"><span style="color:#666666;">Market Expansion Phase</span></span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2011:</strong> Nhi Binh Plastic began trading with the U.S. market and equipped additional mold maintenance machinery to ensure that products met international quality standards.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2012:</strong> The company expanded its export markets to Japan and Spain, successfully meeting the stringent requirements of customers in these demanding markets.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2016:</strong> Nhi Binh Plastic built a new factory in VSIP II, Binh Duong Province, installing 20 injection molding machines, increasing production capacity, and improving working conditions for employees.</span></span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="font-family:Arial,Helvetica,sans-serif;"><span style="line-height:1.1;"><span style="color:#666666;">Present Stage</span></span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2017:</strong> The company achieved international certifications such as ISO 9001:2015, ISO 14001:2015, and OHSAS 18001:2007, elevating its reputation and quality in the global market.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2020:</strong> Nhi Binh Plastic passed the BSCI audit, reaffirming its commitment to social responsibility in manufacturing. In the same year, the company also passed the FCCA & SCS audits to supply products to Walmart.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2021:</strong> Installed a solar panel system over 3,500m², saving energy and reducing carbon emissions. The company also passed Walmart’s FCCA and SCS audits.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2022:</strong> Completed the expansion of an additional 2,500m² of new factory space to meet growing production demands. Established a mold-making workshop in Nhi Binh - Hoc Mon, shortening mold production time, reducing costs, and enhancing mold maintenance.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Year 2023:</strong> Implemented ERP Fast Business Online and Base, optimizing processes and increasing management efficiency.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>As of now</strong>, we have over 50 injection molding machines, more than 180 staff and workers, with a production output of over 200 tons per month.</span></span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="line-height:1.1;"><span style="color:#666666;"><strong>Future Vision</strong></span></span></span></span></h2>



<p style="text-align: justify;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><span style="line-height:1.1;"><span style="color:#666666;">Nhi Binh Plastic aims to become one of the leading companies in the plastic industry. We are committed to innovation and sustainable development, believing that the core values that have led to our success will continue to guide us into the future.</span></span></span></span></p>

