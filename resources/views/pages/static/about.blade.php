<p style="text-align:justify;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="color:#666666;"><strong> </strong>Established in 2009<strong>,</strong> </span><span style="color:#e74c3c;">Nhi Binh Plastic Company Limited </span><span style="color:#666666;">specializes in manufacturing plastic products using injection molding and extrusion technologies. Beginning with a modest 100m² facility and only 2 injection molding machines, Nhi Binh Plastic has continuously expanded its production scale from 2010 to 2015, reaching 1,500m² in Hoc Mon District, Ho Chi Minh City, along with adding 14 more modern injection molding machines to its production line. </span></span></span></p>



