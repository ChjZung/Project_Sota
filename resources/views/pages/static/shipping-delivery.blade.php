    <div class="content-main w-clear" id="toc-content"><p style="text-align: center;"><span style="font-size:20px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Shipping and Delivery Policy - </strong></span></span><span style="color:#e74c3c;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Nhi Binh Plastic</strong></span></span></span></p>



<p style="text-align: justify;"><span style="color:#e74c3c;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Nhi Binh Plastic</strong></span></span></span><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"> is proud to be a leading manufacturer and supplier of high-quality plastic products, meeting the demands of both domestic and international clients. To provide the best service, we have developed a comprehensive <strong>shipping and delivery policy</strong> to ensure fast, safe, and efficient delivery of goods.</span></span></span></p>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>1. Shipping Scope</strong></span></span></span></h2>



<ul>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Domestic</strong>: Nhi Binh Plastic provides nationwide delivery services, covering all provinces from North to South. We collaborate with trusted shipping partners, ensuring on-time delivery and the protection of product quality throughout the shipping process.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>International</strong>: We offer global shipping services, particularly to key markets such as the USA, Europe, Japan, and Southeast Asia. We work with reputable international shipping partners to ensure that products reach customers quickly and safely.</span></span></span></p>

	</li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>2. Shipping Methods</strong></span></span></span></h2>



<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Depending on the specific requirements of each customer and the nature of the products, Nhi Binh Plastic applies various shipping methods to optimize both cost and delivery time:</span></span></span></p>



<ul>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Trucks</strong>: For large domestic orders, we utilize a fleet of trucks to ensure quick and safe delivery, especially for bulk orders or deliveries over long distances.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Motorbikes</strong>: For smaller, compact orders within city limits or nearby areas, we use motorbike delivery services to ensure fast, same-day deliveries.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Express Delivery Companies</strong>: We partner with reputable express couriers like Viettel Post, Giao Hàng Nhanh (GHN), DHL, and FedEx for quick domestic and international deliveries. This method is ideal for medium to small orders requiring short delivery times.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Sea Freight</strong>: For large export shipments, Nhi Binh Plastic opts for sea freight to ensure cost-effective delivery, suitable for bulk products that do not require urgent shipping.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Air Freight</strong>: For high-value orders or those requiring expedited delivery, we offer air freight services to ensure goods reach customers in the shortest time possible.</span></span></span></p>

	</li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>3. Delivery Time</strong></span></span></span></h2>



<ul>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Domestic Delivery</strong>:</span></span></span></p>



	<ul>

		<li style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Within city limits: 1-2 business days.</span></span></span></li>

		<li style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Out-of-town areas: 3-5 business days.</span></span></span></li>

		<li style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Remote areas: 5-7 business days.</span></span></span></li>

	</ul>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>International Delivery</strong>:</span></span></span></p>



	<ul>

		<li style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Air freight</strong>: 3-7 business days, depending on the destination.</span></span></span></li>

		<li style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Sea freight</strong>: 14-40 business days, depending on the region and shipping conditions.</span></span></span></li>

	</ul>

	</li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>4. Shipping Costs</strong></span></span></span></h2>



<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Nhi Binh Plastic is committed to providing transparent and reasonable shipping costs:</span></span></span></p>



<ul>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Domestic</strong>: Shipping fees are calculated based on the weight, size of the goods, and delivery distance. For large orders, we may offer free shipping or reduced shipping costs.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>International</strong>: International shipping costs are calculated according to the rates of the international shipping partner selected by the customer. We will advise customers to choose the most cost-effective and time-efficient shipping method.</span></span></span></p>

	</li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>5. Order Tracking</strong></span></span></span></h2>



<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Each order is provided with a tracking number after dispatch, allowing customers to easily check the status of their shipment. Through the tracking systems of our shipping partners, customers can receive detailed information on the delivery process.</span></span></span></p>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>6. Responsibility and Cargo Insurance</strong></span></span></span></h2>



<ul>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Domestic</strong>: Nhi Binh Plastic takes responsibility for ensuring the safety of goods during transportation. If any damage or loss occurs due to the fault of Nhi Binh Plastic or our shipping partners, customers will be compensated according to the agreed policies.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>International</strong>: For international orders, we encourage customers to purchase cargo insurance to protect their rights in case of any incidents. Customs duties and other additional fees are the responsibility of the customer.</span></span></span></p>

	</li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><span style="color:#666666;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>7. Return Policy</strong></span></span></span></h2>



<ul>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Domestic</strong>: Customers have the right to inspect the goods before accepting delivery. If any technical defects or discrepancies are found, customers can request an exchange or return within 7 days of receipt.</span></span></span></p>

	</li>

	<li>

	<p style="text-align: justify;"><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>International</strong>: Due to the high cost of international shipping and customs-related factors, Nhi Binh Plastic only accepts returns or exchanges for technical defects from the manufacturer.</span></span></span></p>

	</li>

</ul>



<hr />

<p style="text-align: justify;"><span style="color:#e74c3c;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><strong>Nhi Binh Plastic</strong></span></span></span><span style="color:#666666;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"> is committed to providing top-quality shipping and delivery services, meeting the diverse needs of customers both domestically and internationally.</span></span></span></p>

