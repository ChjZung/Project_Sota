	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Response Time:</strong> We commit to responding to warranty requests within 24 working hours of receiving the notification.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Repairs and Replacements:</strong> Once the defect is confirmed to be within the warranty coverage, we will carry out repairs or replace the defective parts as quickly as possible, typically within 2 to 7 working days.</span></span></span></span></li>

