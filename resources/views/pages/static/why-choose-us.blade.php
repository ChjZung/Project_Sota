<h2 style="text-align: justify;"><strong><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">A</span></span><span style="font-size:18px;"><span style="font-family:Arial,Helvetica,sans-serif;">dvanced Machinery and Automation</span></span></span></strong></h2>



<p style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Nhi Binh Plastic is equipped with over 50 highly automated injection molding machines, with clamping forces ranging from 75 tons to 600 tons, allowing for the production of various products, from small to large, with a maximum weight of up to 2kg and dimensions of up to 700mm. Our current capacity allows for the production of over 200 tons per month and over 10 million units per month.</span></span></span></p>



<p style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Our modern machinery optimizes the high-quality plastic processing workflow, ensuring consistent and stable product quality. </span></span></span></p>



