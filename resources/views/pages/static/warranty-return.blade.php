<p style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;">At Nhi Binh Plastic Company, we are committed to providing our customers with high-quality plastic injection molds, backed by the following warranty policy:</span></span></span></span></p>



<h3 style="text-align: justify;"><span style="color:#666666;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;">Mold Warranty Period</span></span></span></strong></span></h3>



