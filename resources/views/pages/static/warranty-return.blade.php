	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Components Covered: </strong>The warranty fully covers all parts of the molds, including mold cores, slides, inserts, guide pins, hot runners, cooling systems, and other related components.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Exclusions:</strong> The warranty does not cover damages caused by improper use, lack of maintenance, or unauthorized modifications by third parties without Nhi Binh Plastic's consent.</span></span></span></span></li>

</ul>



<h3 style="text-align: justify;"><span style="color:#666666;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;">Mold Warranty Conditions</span></span></span></strong></span></h3>



<ul>

	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Usage Conditions:</strong> The molds must be operated and maintained according to Nhi Binh Plastic's technical guidelines.</span></span></span></span></li>

	<li style="text-align: justify;"><span style="color:#666666;"><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;"><span style="font-size:16px;"><strong>Periodic Inspections:</strong> Customers are required to perform regular inspections and maintenance to ensure the molds operate effectively and achieve optimal longevity.</span></span></span></span></li>

</ul>



