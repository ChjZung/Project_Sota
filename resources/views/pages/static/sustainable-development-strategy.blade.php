            <div class="content-main w-clear" id="toc-content"><p style="text-align: center;"><span style="font-size:20px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Nhi Binh Plastic’s Sustainable Development Direction</span></span></strong></span></p>



<p> </p>



<h2><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Vision</span></span></strong></span></h2>



<p style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">To become a leading plastic manufacturing company, pioneering in sustainable production solutions, fostering close partnerships, contributing to environmental protection, and enhancing the quality of life for the community.</span></span></span></p>



<h2><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Mission</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Produce high-quality, safe, and environmentally friendly plastic products.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Optimize processes, minimize waste, and conserve energy.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Build a professional work environment with social responsibility.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Contribute positively to the sustainable development of the community. </span></span></span></li>

</ul>



<p style="text-align: justify;"> </p>



<p style="text-align: center;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;"><img alt="Nhi Binh Plastic " src="/upload/elfinder/Nhi%20Binh%20Plastic%20-%20sustainable%20development.jpg" style="width: 700px; height: 350px;" /></span></span></span></p>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Green Production</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">We have invested in equipment and implemented processes that ensure 100% closed-loop recycling of defective products and plastic runners.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Utilize internationally certified recycled plastics, aiming towards the use of PCR (Post-Consumer Recycled) plastics.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Focus on the research and development of biodegradable plastic products.</span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Green Energy</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Since 2021, we have invested in a solar energy system covering 3,500m², with plans to expand by an additional 2,500m² in the near future.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Nhi Binh Plastic uses injection molding machines equipped with energy-saving servo motors and plans to transition to fully electric machines.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">We use LED lighting systems in our factories and solar-powered lighting in surrounding areas. </span></span></span></li>

</ul>



<p style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">​​​​​​​</span></span></span></p>



<p style="text-align: center;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">​​​​​​​<img alt="Solor Nhi Binh Plastic 3500m2" src="/upload/elfinder/Nhua%20Nhi%20Binh%20-%20Nang%20luong%20mat%20troi.jpg" style="width: 700px; height: 350px;" /></span></span></span></p>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Water and Waste Management</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Nhi Binh Plastic’s factories meet the standards for treating domestic wastewater, and we have implemented a closed-loop system for 100% water reuse in production.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">We strictly control and enforce solid waste segregation and recycling processes, partnering with environmentally friendly waste management companies.</span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Community Development</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Training and Development: Regular skill enhancement training for employees, focusing on plastics, mold-making, quality management, and sustainable development.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Employee Well-being: Organize cultural, sports, and travel activities, and provide tuition support for employees' children.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">BSCI Certification: Nhi Binh Plastic has achieved BSCI certification for over six years, committed to strict adherence to BSCI standards, Vietnamese laws, and ensuring social responsibility and workers' rights.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Social Activities: Participate in charitable activities and community support, with a particular focus on environmental protection and education. </span></span></span></li>

</ul>



<p style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">​​​​​​​​​​​​​​</span></span></span></p>



<p style="text-align: center;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">​​​​​​​<img alt="Team building Nhi Binh Plastic" src="/upload/elfinder/Team%20building%20Nhi%20Binh%20Plastic.jpg" style="width: 700px; height: 350px;" />​​​​​​​</span></span></span></p>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Technological and Management Innovation</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Invest in modern, automated production technologies to enhance productivity and quality.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Maintain and continuously improve the quality management systems according to ISO 9001:2015, ISO 14001:2015, and BSCI standards.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Digitize management processes using ERP Fast Online and Base systems.</span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Enhancing Competitiveness</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Innovate products and quality to meet market demands with advanced technology.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Strengthen brand building and increase recognition domestically and internationally.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Train and upskill employees, creating a professional and creative workforce.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Regularly assess and improve production and business efficiency to meet sustainable development indicators.</span></span></span></li>

</ul>



<h2 style="text-align: justify;"><span style="font-size:18px;"><strong><span style="line-height:1.1;"><span style="font-family:Arial,Helvetica,sans-serif;">Sustainable Partnerships</span></span></strong></span></h2>



<ul>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Collaborate with reputable suppliers who share our sustainable development goals.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Establish long-term partnerships with strategic customers, develop new products, and increase the use of PCR plastics, biodegradable plastics, and eco-friendly packaging solutions.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">Engage in industry associations and environmental organizations to stay updated, share experiences, and expand cooperation.</span></span></span></li>

	<li style="text-align: justify;"><span style="line-height:1.1;"><span style="font-size:16px;"><span style="font-family:Arial,Helvetica,sans-serif;">With a clear sustainable development strategy and concrete actions, Nhi Binh Plastic is confident in its path to success, making a positive contribution to society's progress.</span></span></span></li>

</ul>

